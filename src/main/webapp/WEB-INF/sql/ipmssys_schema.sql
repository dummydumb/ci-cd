-- ============================================================================
--  IPMSSYS — Full Database Schema (Oracle 12c)
--  Input Plan Management System
--
--  One consolidated DDL for every table, sequence, index and constraint the
--  application uses. Column names, types and sequence names match the DAO code
--  exactly. Run top-to-bottom on a fresh schema; tables are ordered so every
--  foreign key's parent is created first.
--
--  Pipeline: MONTHLY_PLAN → PRECONDITION_RAW → SAGGERING(+ITEM+DAY)
--            → MACHINE_ALLOCATION(+GROUP+ITEM+MACHINE) → PLOTTING_SUMMARY(+DETAIL)
--            → LOADING_PLAN_OVERRIDE / _FRACTION_PLOT / _ITEM_PRIORITY
--
--  Reference data: ACCOUNT, MACHINE_TYPE, MACHINE, ITEM, ITEM_MACHINE
--
--  Conventions: NUMBER(19) for sequence PKs/FKs, snake_case columns,
--  CREATED_AT/UPDATED_AT default SYSTIMESTAMP, ON DELETE CASCADE down the tree.
-- ============================================================================


-- ############################################################################
--  SECTION 1 — REFERENCE / MASTER DATA
-- ############################################################################

-- ----------------------------------------------------------------------------
--  ACCOUNT — application users (login)
-- ----------------------------------------------------------------------------
CREATE TABLE ACCOUNT (
    ACCOUNT_ID      NUMBER(19)     NOT NULL,
    EMPLOYEE_ID     VARCHAR2(40)   NOT NULL,
    PASSWORD        VARCHAR2(200)  NOT NULL,
    FIRST_NAME      VARCHAR2(80),
    LAST_NAME       VARCHAR2(80),
    ACCESS_LEVEL    VARCHAR2(30)   DEFAULT 'USER' NOT NULL,
    EMAIL           VARCHAR2(120),
    PW_EXPIRATION   DATE,
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
    CONSTRAINT UQ_ACCOUNT_EMPLOYEE UNIQUE (EMPLOYEE_ID)
);
CREATE SEQUENCE ACCOUNT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- ----------------------------------------------------------------------------
--  MACHINE_TYPE — e.g. FRST, firing line type
-- ----------------------------------------------------------------------------
CREATE TABLE MACHINE_TYPE (
    MACHINE_TYPE_ID NUMBER(19)     NOT NULL,
    MACHINE_CODE    VARCHAR2(40)   NOT NULL,
    MACHINE_NAME    VARCHAR2(120)  NOT NULL,
    STATUS          VARCHAR2(20)   DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MACHINE_TYPE PRIMARY KEY (MACHINE_TYPE_ID),
    CONSTRAINT UQ_MACHINE_TYPE_CODE UNIQUE (MACHINE_CODE)
);
CREATE SEQUENCE MACHINE_TYPE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- ----------------------------------------------------------------------------
--  MACHINE — individual machines, each of a machine type
-- ----------------------------------------------------------------------------
CREATE TABLE MACHINE (
    MACHINE_ID      NUMBER(19)     NOT NULL,
    MACHINE_NAME    VARCHAR2(60)   NOT NULL,
    MACHINE_TYPE_ID NUMBER(19)     NOT NULL,
    MACHINE_USAGE   VARCHAR2(20)   DEFAULT 'AVAILABLE' NOT NULL,
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MACHINE PRIMARY KEY (MACHINE_ID),
    CONSTRAINT UQ_MACHINE_NAME UNIQUE (MACHINE_NAME),
    CONSTRAINT FK_MACHINE_TYPE FOREIGN KEY (MACHINE_TYPE_ID)
        REFERENCES MACHINE_TYPE (MACHINE_TYPE_ID)
);
CREATE INDEX IX_MACHINE_TYPE ON MACHINE (MACHINE_TYPE_ID);
CREATE SEQUENCE MACHINE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- ----------------------------------------------------------------------------
--  ITEM — products, each in a firing GROUP_CODE (A/B)
-- ----------------------------------------------------------------------------
CREATE TABLE ITEM (
    ITEM_ID         NUMBER(19)     NOT NULL,
    ITEM_NAME       VARCHAR2(120)  NOT NULL,
    GROUP_CODE      VARCHAR2(10),
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ITEM PRIMARY KEY (ITEM_ID),
    CONSTRAINT UQ_ITEM_NAME UNIQUE (ITEM_NAME)
);
CREATE SEQUENCE ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- ----------------------------------------------------------------------------
--  ITEM_MACHINE — which machines each item is QUALIFIED to run on (M:N)
-- ----------------------------------------------------------------------------
CREATE TABLE ITEM_MACHINE (
    ITEM_MACHINE_ID NUMBER(19)     NOT NULL,
    ITEM_ID         NUMBER(19)     NOT NULL,
    MACHINE_ID      NUMBER(19)     NOT NULL,
    CONSTRAINT PK_ITEM_MACHINE PRIMARY KEY (ITEM_MACHINE_ID),
    CONSTRAINT UQ_ITEM_MACHINE UNIQUE (ITEM_ID, MACHINE_ID),
    CONSTRAINT FK_IM_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES ITEM (ITEM_ID) ON DELETE CASCADE,
    CONSTRAINT FK_IM_MACHINE FOREIGN KEY (MACHINE_ID)
        REFERENCES MACHINE (MACHINE_ID) ON DELETE CASCADE
);
CREATE INDEX IX_IM_ITEM    ON ITEM_MACHINE (ITEM_ID);
CREATE INDEX IX_IM_MACHINE ON ITEM_MACHINE (MACHINE_ID);
CREATE SEQUENCE ITEM_MACHINE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


-- ############################################################################
--  SECTION 2 — THE MONTHLY PLAN ROOT
-- ############################################################################

-- ----------------------------------------------------------------------------
--  MONTHLY_PLAN — one plan per (month, machine type). Root of the pipeline.
--    PLAN_MONTH is always the 1st of the month.
-- ----------------------------------------------------------------------------
CREATE TABLE MONTHLY_PLAN (
    PLAN_ID             NUMBER(19)     NOT NULL,
    PLAN_MONTH          DATE           NOT NULL,
    MACHINE_TYPE_ID     NUMBER(19)     NOT NULL,
    DESCRIPTION         VARCHAR2(400),
    PRODUCTION_TIME     NUMBER(10)     DEFAULT 0 NOT NULL,   -- minutes/day
    EFFICIENCY          NUMBER(5)      DEFAULT 0 NOT NULL,   -- percent 0..100
    WORKING_DAYS        NUMBER(5)      DEFAULT 0 NOT NULL,
    AVAILABLE_MACHINE   NUMBER(10)     DEFAULT 0 NOT NULL,
    STATUS              VARCHAR2(20)   DEFAULT 'DRAFT' NOT NULL,  -- DRAFT|ACTIVE|CLOSED
    LAST_DAY_PRODUCTION DATE,
    CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MONTHLY_PLAN PRIMARY KEY (PLAN_ID),
    CONSTRAINT UQ_MONTHLY_PLAN UNIQUE (PLAN_MONTH, MACHINE_TYPE_ID),
    CONSTRAINT FK_MP_TYPE FOREIGN KEY (MACHINE_TYPE_ID)
        REFERENCES MACHINE_TYPE (MACHINE_TYPE_ID)
);
CREATE INDEX IX_MP_TYPE ON MONTHLY_PLAN (MACHINE_TYPE_ID);
CREATE SEQUENCE MONTHLY_PLAN_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


-- ############################################################################
--  SECTION 3 — STAGE 1: PRECONDITION RAW (per-item raw inputs)
-- ############################################################################

CREATE TABLE PRECONDITION_RAW (
    PRECONDITION_RAW_ID NUMBER(19)     NOT NULL,
    PLAN_ID             NUMBER(19)     NOT NULL,
    ITEM_ID             NUMBER(19)     NOT NULL,
    CAP_CODE            VARCHAR2(60),
    LOTS_PER_BATCH      NUMBER(10)     DEFAULT 0 NOT NULL,
    INTERNAL_SHEET      NUMBER(10)     DEFAULT 0 NOT NULL,
    DUMMY_SHEET         NUMBER(10)     DEFAULT 0 NOT NULL,
    BLK_PER_LOT         NUMBER(10)     DEFAULT 0 NOT NULL,
    KPCS_PER_LOT        NUMBER(18,6)   DEFAULT 0 NOT NULL,
    SEC_PER_SHT         NUMBER(18,6)   DEFAULT 0 NOT NULL,
    EFF                 NUMBER(9,6)    DEFAULT 0 NOT NULL,   -- per-item conversion eff (decimal, 0.75 = 75%)
    LOTS_PER_MONTH      NUMBER(12)     DEFAULT 0 NOT NULL,
    CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PRECONDITION_RAW PRIMARY KEY (PRECONDITION_RAW_ID),
    CONSTRAINT UQ_PRECONDITION_RAW UNIQUE (PLAN_ID, ITEM_ID),
    CONSTRAINT FK_PR_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PR_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES ITEM (ITEM_ID)
);
CREATE INDEX IX_PR_PLAN ON PRECONDITION_RAW (PLAN_ID);
CREATE SEQUENCE PRECONDITION_RAW_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- NOTE: STAGE 2 (Precondition / capacity engine) is COMPUTED on the fly by
-- PreconditionService from PRECONDITION_RAW + the plan header + saggered lots.
-- It is not stored, so there is no PRECONDITION table.


-- ############################################################################
--  SECTION 4 — SAGGERING (batch size + per-day batch pattern)
-- ############################################################################

-- Header: one saggering per plan
CREATE TABLE SAGGERING (
    SAGGERING_ID    NUMBER(19)      NOT NULL,
    PLAN_ID         NUMBER(19)      NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'DRAFT' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SAGGERING PRIMARY KEY (SAGGERING_ID),
    CONSTRAINT UQ_SAGGERING_PLAN UNIQUE (PLAN_ID),
    CONSTRAINT FK_SAGGERING_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE
);
CREATE SEQUENCE SAGGERING_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Item: one row per item in a saggering, with its batch size
CREATE TABLE SAGGERING_ITEM (
    SAGGERING_ITEM_ID   NUMBER(19)      NOT NULL,
    SAGGERING_ID        NUMBER(19)      NOT NULL,
    ITEM_ID             NUMBER(19)      NOT NULL,
    CAP_CODE            VARCHAR2(60),
    LOTS_PER_BATCH      NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SAGGERING_ITEM PRIMARY KEY (SAGGERING_ITEM_ID),
    CONSTRAINT UQ_SAGGERING_ITEM UNIQUE (SAGGERING_ID, ITEM_ID),
    CONSTRAINT FK_SI_SAGGERING FOREIGN KEY (SAGGERING_ID)
        REFERENCES SAGGERING (SAGGERING_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SI_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES ITEM (ITEM_ID)
);
CREATE INDEX IX_SI_SAGGERING ON SAGGERING_ITEM (SAGGERING_ID);
CREATE SEQUENCE SAGGERING_ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Day: per-day batch value for a saggering item
CREATE TABLE SAGGERING_DAY (
    SAGGERING_DAY_ID    NUMBER(19)      NOT NULL,
    SAGGERING_ITEM_ID   NUMBER(19)      NOT NULL,
    PLAN_DATE           DATE            NOT NULL,
    VALUE               NUMBER(10)      DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SAGGERING_DAY PRIMARY KEY (SAGGERING_DAY_ID),
    CONSTRAINT UQ_SAGGERING_DAY UNIQUE (SAGGERING_ITEM_ID, PLAN_DATE),
    CONSTRAINT FK_SD_ITEM FOREIGN KEY (SAGGERING_ITEM_ID)
        REFERENCES SAGGERING_ITEM (SAGGERING_ITEM_ID) ON DELETE CASCADE
);
CREATE INDEX IX_SD_ITEM ON SAGGERING_DAY (SAGGERING_ITEM_ID);
CREATE SEQUENCE SAGGERING_DAY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


-- ############################################################################
--  SECTION 5 — STAGE 3: MACHINE ALLOCATION (auto-compute + manual override)
-- ############################################################################

-- Header: one allocation per plan
CREATE TABLE MACHINE_ALLOCATION (
    ALLOCATION_ID   NUMBER(19)      NOT NULL,
    PLAN_ID         NUMBER(19)      NOT NULL,
    FIX_LIMIT       NUMBER(10)      DEFAULT 30 NOT NULL,
    STATUS          VARCHAR2(20)    DEFAULT 'SAVED' NOT NULL,
    CREATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_MACHINE_ALLOCATION PRIMARY KEY (ALLOCATION_ID),
    CONSTRAINT UQ_MACHINE_ALLOCATION_PLAN UNIQUE (PLAN_ID),
    CONSTRAINT FK_MA_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE
);
CREATE SEQUENCE MACHINE_ALLOCATION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Group: firing group + material grouping, with fix/fraction requirements
CREATE TABLE MACHINE_ALLOCATION_GROUP (
    GROUP_ID               NUMBER(19)   NOT NULL,
    ALLOCATION_ID          NUMBER(19)   NOT NULL,
    GROUP_NO               NUMBER(10)   DEFAULT 0 NOT NULL,
    GROUP_CODE             VARCHAR2(10),
    MATERIAL_CODE          VARCHAR2(60),
    MERGE_KEY              VARCHAR2(120),
    GROUPING_MC_PER_DAY    NUMBER(18,6) DEFAULT 0 NOT NULL,
    FIX_REQUIREMENT        NUMBER(18,6) DEFAULT 0 NOT NULL,
    FRACTION1_REQUIREMENT  NUMBER(18,6) DEFAULT 0 NOT NULL,
    STATUS                 VARCHAR2(20) DEFAULT 'OK' NOT NULL,
    CONSTRAINT PK_MA_GROUP PRIMARY KEY (GROUP_ID),
    CONSTRAINT FK_MAG_ALLOC FOREIGN KEY (ALLOCATION_ID)
        REFERENCES MACHINE_ALLOCATION (ALLOCATION_ID) ON DELETE CASCADE
);
CREATE INDEX IX_MAG_ALLOC ON MACHINE_ALLOCATION_GROUP (ALLOCATION_ID);
CREATE SEQUENCE MACHINE_ALLOCATION_GROUP_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Item: the items that belong to a group (ITEM_ID here is the row PK, from a sequence)
CREATE TABLE MACHINE_ALLOCATION_ITEM (
    ITEM_ID         NUMBER(19)      NOT NULL,
    GROUP_ID        NUMBER(19)      NOT NULL,
    ALLOCATION_ID   NUMBER(19)      NOT NULL,
    ITEM_NAME       VARCHAR2(120),
    ITEM_SEQ        NUMBER(10)      DEFAULT 0 NOT NULL,
    MC_PER_DAY      NUMBER(18,6)    DEFAULT 0 NOT NULL,
    GROUP_CODE      VARCHAR2(10),
    MATERIAL_CODE   VARCHAR2(60),
    CONSTRAINT PK_MA_ITEM PRIMARY KEY (ITEM_ID),
    CONSTRAINT FK_MAI_GROUP FOREIGN KEY (GROUP_ID)
        REFERENCES MACHINE_ALLOCATION_GROUP (GROUP_ID) ON DELETE CASCADE
);
CREATE INDEX IX_MAI_GROUP ON MACHINE_ALLOCATION_ITEM (GROUP_ID);
CREATE SEQUENCE MACHINE_ALLOCATION_ITEM_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Machine: the machines assigned to a group (FIX or FRACTION1) with its requirement share
CREATE TABLE MACHINE_ALLOCATION_MACHINE (
    MACHINE_ENTRY_ID   NUMBER(19)    NOT NULL,
    GROUP_ID           NUMBER(19)    NOT NULL,
    MACHINE_ROLE       VARCHAR2(20)  NOT NULL,   -- FIX | FRACTION1
    MACHINE_SEQ        NUMBER(10)    DEFAULT 0 NOT NULL,
    MACHINE_NAME       VARCHAR2(60),
    REQUIREMENT_VALUE  NUMBER(18,6)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_MA_MACHINE PRIMARY KEY (MACHINE_ENTRY_ID),
    CONSTRAINT FK_MAM_GROUP FOREIGN KEY (GROUP_ID)
        REFERENCES MACHINE_ALLOCATION_GROUP (GROUP_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_MAM_ROLE CHECK (MACHINE_ROLE IN ('FIX','FRACTION1'))
);
CREATE INDEX IX_MAM_GROUP ON MACHINE_ALLOCATION_MACHINE (GROUP_ID);
CREATE SEQUENCE MACHINE_ALLOCATION_MACHINE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


-- ############################################################################
--  SECTION 6 — PLOTTING SUMMARY (maintenance stoppages that block machine-days)
-- ############################################################################

-- Header: one stoppage record (PM / Evaluation / ME Improvement, etc.)
CREATE TABLE PLOTTING_SUMMARY (
    PLOTTING_ID         NUMBER(19)     NOT NULL,
    EVALUATION          VARCHAR2(60),
    CATEGORY            VARCHAR2(60),
    TYPE                VARCHAR2(60),
    ITEM_ID             NUMBER(19),
    ITEM_TYPE           VARCHAR2(60),
    PLAN                VARCHAR2(60),
    NO_OF_LOTS          NUMBER(12)     DEFAULT 0 NOT NULL,
    WOS_TYPE            VARCHAR2(60),
    MACHINE_TYPE_ID     NUMBER(19)     NOT NULL,
    STACKING_MACHINE_ID NUMBER(19),
    DATE_PREFERRED      DATE,
    CONFIRMED_DATE      DATE,
    PIC                 VARCHAR2(120),
    CREATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PLOTTING_SUMMARY PRIMARY KEY (PLOTTING_ID),
    CONSTRAINT FK_PS_TYPE FOREIGN KEY (MACHINE_TYPE_ID)
        REFERENCES MACHINE_TYPE (MACHINE_TYPE_ID),
    CONSTRAINT FK_PS_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES ITEM (ITEM_ID),
    CONSTRAINT FK_PS_MACHINE FOREIGN KEY (STACKING_MACHINE_ID)
        REFERENCES MACHINE (MACHINE_ID)
);
CREATE INDEX IX_PS_TYPE    ON PLOTTING_SUMMARY (MACHINE_TYPE_ID);
CREATE INDEX IX_PS_MACHINE ON PLOTTING_SUMMARY (STACKING_MACHINE_ID);
CREATE SEQUENCE PLOTTING_SUMMARY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Detail: the per-day schedule + blocked hours for a stoppage (date range → days)
CREATE TABLE PLOTTING_SUMMARY_DETAIL (
    DETAIL_ID       NUMBER(19)      NOT NULL,
    PLOTTING_ID     NUMBER(19)      NOT NULL,
    SCHEDULE_DATE   DATE            NOT NULL,
    HOURS           NUMBER(9,4)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PS_DETAIL PRIMARY KEY (DETAIL_ID),
    CONSTRAINT UQ_PS_DETAIL UNIQUE (PLOTTING_ID, SCHEDULE_DATE),
    CONSTRAINT FK_PSD_PLOTTING FOREIGN KEY (PLOTTING_ID)
        REFERENCES PLOTTING_SUMMARY (PLOTTING_ID) ON DELETE CASCADE
);
CREATE INDEX IX_PSD_PLOTTING ON PLOTTING_SUMMARY_DETAIL (PLOTTING_ID);
CREATE SEQUENCE PLOTTING_SUMMARY_DETAIL_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


-- ############################################################################
--  SECTION 7 — STAGE 4: LOADING PLAN (only the planner's manual data persists;
--              the machines x days grid itself is computed by LoadingPlanService)
-- ############################################################################

-- Cell overrides: manual value edits + the manual Excel-style status flag.
--   CELL_STATUS mirrors the Excel '4. Loading Plan' colour legend; the planner
--   sets it by hand (purple = NEEDS_CONVERSION). Nothing is auto-set.
CREATE TABLE LOADING_PLAN_OVERRIDE (
    OVERRIDE_ID          NUMBER(19)     NOT NULL,
    PLAN_ID              NUMBER(19)     NOT NULL,
    MACHINE_NAME         VARCHAR2(60)   NOT NULL,
    ITEM_NAME            VARCHAR2(120)  NOT NULL,
    PLAN_DATE            DATE           NOT NULL,
    OVERRIDE_VALUE       NUMBER(12,2)   DEFAULT 0 NOT NULL,
    REASSIGN_REASON      VARCHAR2(40),
    OVERRIDE_TYPE        VARCHAR2(20)   DEFAULT 'STANDARD' NOT NULL,
    REMARKS              VARCHAR2(400),
    RECOVERY_SOURCE_DATE DATE,
    CELL_STATUS          VARCHAR2(20)   DEFAULT 'NONE' NOT NULL,
    CREATED_AT           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LP_OVERRIDE PRIMARY KEY (OVERRIDE_ID),
    CONSTRAINT UQ_LP_OVERRIDE UNIQUE (PLAN_ID, MACHINE_NAME, ITEM_NAME, PLAN_DATE),
    CONSTRAINT FK_LPO_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_LPO_OVERRIDE_TYPE
        CHECK (OVERRIDE_TYPE IN ('STANDARD','RECOVERY','CONVERSION')),
    CONSTRAINT CHK_LPO_CELL_STATUS
        CHECK (CELL_STATUS IN ('NONE','PM','TROUBLE','EVALUATION','ADVANCE',
                               'ME_IMPROVEMENT','NEEDS_CONVERSION','OK_SUBMITTED'))
);
CREATE INDEX IX_LPO_PLAN ON LOADING_PLAN_OVERRIDE (PLAN_ID);
CREATE SEQUENCE LOADING_PLAN_OVERRIDE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Extended fraction plots: planner-defined date range + total lots on a machine/item
CREATE TABLE LOADING_PLAN_FRACTION_PLOT (
    PLOT_ID         NUMBER(19)     NOT NULL,
    PLAN_ID         NUMBER(19)     NOT NULL,
    MACHINE_NAME    VARCHAR2(60)   NOT NULL,
    ITEM_NAME       VARCHAR2(120)  NOT NULL,
    PLOT_START      DATE           NOT NULL,
    PLOT_END        DATE           NOT NULL,
    TOTAL_LOTS      NUMBER(12)     DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LP_FRACTION_PLOT PRIMARY KEY (PLOT_ID),
    CONSTRAINT FK_LPFP_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE
);
CREATE INDEX IX_LPFP_PLAN ON LOADING_PLAN_FRACTION_PLOT (PLAN_ID);
CREATE SEQUENCE LP_FRACTION_PLOT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

-- Per-machine item run order
CREATE TABLE LOADING_PLAN_ITEM_PRIORITY (
    PRIORITY_ID     NUMBER(19)     NOT NULL,
    PLAN_ID         NUMBER(19)     NOT NULL,
    MACHINE_NAME    VARCHAR2(60)   NOT NULL,
    ITEM_NAME       VARCHAR2(120)  NOT NULL,
    PRIORITY_SEQ    NUMBER(10)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_LP_ITEM_PRIORITY PRIMARY KEY (PRIORITY_ID),
    CONSTRAINT UQ_LP_ITEM_PRIORITY UNIQUE (PLAN_ID, MACHINE_NAME, ITEM_NAME),
    CONSTRAINT FK_LPIP_PLAN FOREIGN KEY (PLAN_ID)
        REFERENCES MONTHLY_PLAN (PLAN_ID) ON DELETE CASCADE
);
CREATE INDEX IX_LPIP_PLAN ON LOADING_PLAN_ITEM_PRIORITY (PLAN_ID);
CREATE SEQUENCE LP_ITEM_PRIORITY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;


